export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = messages[lang][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

const countryKeys: Record<string, MessageKey> = {
  AT: "countryAT",
  DE: "countryDE",
  HU: "countryHU",
  IT: "countryIT",
  CH: "countryCH",
  SI: "countrySI",
};

export function countryLabel(lang: Lang, code: string): string {
  const key = countryKeys[code];
  return key ? translate(lang, key) : code;
}

export function regionLabel(lang: Lang, region: string): string {
  return region
    .split(" / ")
    .map((part) => {
      const key = regionKeys[part];
      return key ? translate(lang, key) : part;
    })
    .join(" / ");
}

export function bracketLabel(lang: Lang, id: string, fallback: string): string {
  const key = bracketKeys[id] ?? bracketKeys[id.toLowerCase()];
  return key ? translate(lang, key) : fallback;
}

export function deadlineLabel(lang: Lang, id: string, fallback: string): string {
  const key = deadlineKeys[id];
  return key ? translate(lang, key) : fallback;
}

export function priceReasonText(
  lang: Lang,
  reason: PriceReason | null,
  bracketId: string | null,
  nextStart: string | null,
): string {
  if (bracketId === "child") return translate(lang, "childUnknown");
  if (reason === "no-birth-year") return translate(lang, "noBirthYear");
  if (reason === "age-not-birth-year") return translate(lang, "ageNotBirthYear");
  if (reason === "no-bracket") return translate(lang, "noBracket");
  if (reason === "no-period") {
    return nextStart ? translate(lang, "presaleNotStarted", { date: formatDate(lang, nextStart) }) : translate(lang, "priceUnknown");
  }
  if (reason === "price-unknown") return translate(lang, "afterDeadline");
  return translate(lang, "priceUnknown");
}
