const messages: Record<Lang, Record<MessageKey, string>> = { en, hu };

const regionKeys: Record<string, MessageKey> = {
  "Lower Austria": "regionLowerAustria",
  Styria: "regionStyria",
  "Styria / Carinthia": "regionStyriaCarinthia",
  Tirol: "regionTirol",
};

const bracketKeys: Record<string, MessageKey> = {
  adult: "bracketAdult",
  u25: "bracketU25",
  u28: "bracketU28",
  child: "bracketChild",
  standard: "bracketStandard",
};

const deadlineKeys: Record<string, MessageKey> = {
  "bep-early": "deadlineBepEarly",
  "bep-november": "deadlineBepNovember",
  "tsc-start": "deadlineTscStart",
  "tsc-end": "deadlineTscEnd",
  "sj-early": "deadlineSjEarly",
  "ssc-early": "deadlineSscEarly",
  "mmt-u28": "deadlineMmtU28",
};

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = messages[lang][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function regionLabel(lang: Lang, region: string): string {
  const key = regionKeys[region];
  return key ? translate(lang, key) : region;
}

export function bracketLabel(lang: Lang, id: string, fallback: string): string {
  const key = bracketKeys[id];
  return key ? translate(lang, key) : fallback;
}

export function deadlineLabel(lang: Lang, id: string, fallback: string): string {
  const key = deadlineKeys[id];
  return key ? translate(lang, key) : fallback;
}

export function cityNoteLabel(lang: Lang, note: string | null): string | null {
  if (note === "home") return translate(lang, "cityNoteHome");
  if (note === "study") return translate(lang, "cityNoteStudy");
  return note;
}

export function priceReasonText(
  lang: Lang,
  reason: PriceReason | null,
  bracketId: string | null,
  nextStart: string | null,
): string {
  if (bracketId === "child") return translate(lang, "childUnknown");
  if (reason === "no-birth-year") return translate(lang, "noBirthYear");
  if (reason === "no-bracket") return translate(lang, "noBracket");
  if (reason === "no-period") {
    return nextStart ? translate(lang, "presaleNotStarted", { date: formatDate(lang, nextStart) }) : translate(lang, "priceUnknown");
  }
  if (reason === "price-unknown") return translate(lang, "afterDeadline");
  return translate(lang, "priceUnknown");
}
